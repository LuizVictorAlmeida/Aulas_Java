package aula2.exercicios;

public class Exercicio06 {
    static void main(String[] args) {
        int valor1 = 33;
        int valor2 = 3;

        System.out.println("Valor 1 = "+valor1);
        System.out.println("Valor 2 = "+valor2);
        System.out.println("");
        System.out.println("Valor 1 > Valor 2 = "+(valor1 > valor2));
        System.out.println("Valor 1 < Valor 2 = "+(valor1 < valor2));
        System.out.println("Valor 1 >= Valor 2 = "+(valor1 >= valor2));
        System.out.println("Valor 1 <= Valor 2 = "+(valor1 <= valor2));
        System.out.println("Valor 1 == Valor 2 = "+(valor1 == valor2));
        System.out.println("Valor 1 != Valor 2 = "+(valor1 != valor2));
    }
}
